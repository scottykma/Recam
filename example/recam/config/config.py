class ContextNoiseRegime(IntEnum):
    """How one micro-step pairs the context timestep with the main one.

    NORMAL     t_context and t_main are the min and max of two main draws
    SAME_NOISE both take the same single main draw
    HIGH_HIGH  both take one uniform draw from `high_noise_timestep_range`
    """

    NORMAL = 0
    SAME_NOISE = 1
    HIGH_HIGH = 2

    @property
    def key(self) -> str:
        """Name of this regime's weight in `context_noise_mixture_probs`."""
        return self.name.lower()


@dataclass
class StrategyConfig:
    flow_num_train_timesteps: int = 1000
    flow_shift: float = 5.0
    flow_snr_type: Literal["uniform", "lognorm", "mode"] = "lognorm"
    flow_min_timestep: float = 0.0
    flow_max_timestep: float | None = None
    dropout_cond_prob: float = 0.1
    main_lognorm_mu: float = 0.0
    context_noise_mixture_probs: dict[str, float] = field(
        default_factory=lambda: {
            ContextNoiseRegime.NORMAL.key: 0.90,
            ContextNoiseRegime.SAME_NOISE.key: 0.05,
            ContextNoiseRegime.HIGH_HIGH.key: 0.05,
        }
    )
    high_noise_timestep_range: tuple[float, float] = (0.95, 1.0)

    def __post_init__(self) -> None:
        mixture = {
            str(name): float(prob)
            for name, prob in self.context_noise_mixture_probs.items()
        }
        expected = {regime.key for regime in ContextNoiseRegime}
        if set(mixture) != expected:
            raise ValueError(
                "strategy.context_noise_mixture_probs must name every regime "
                f"exactly once, {sorted(expected)}; got {sorted(mixture)}"
            )
        if any(
            not math.isfinite(prob) or prob < 0 for prob in mixture.values()
        ) or sum(mixture.values()) <= 0:
            raise ValueError(
                "strategy.context_noise_mixture_probs must be non-negative "
                "finite weights with positive mass"
            )
        total = sum(mixture.values())
        self.context_noise_mixture_probs = {
            name: prob / total for name, prob in mixture.items()
        }

        high_range = tuple(self.high_noise_timestep_range)
        if (
            len(high_range) != 2
            or any(not math.isfinite(value) for value in high_range)
            or not 0.0 <= high_range[0] < high_range[1] <= 1.0
        ):
            raise ValueError(
                "strategy.high_noise_timestep_range must be a finite, "
                "increasing [low, high] interval within [0, 1]"
            )
        self.high_noise_timestep_range = high_range

    @property
    def mixture_weights(self) -> tuple[float, ...]:
        """`context_noise_mixture_probs` in `ContextNoiseRegime` order."""
        return tuple(
            self.context_noise_mixture_probs[regime.key]
            for regime in ContextNoiseRegime
        )


@dataclass
class ExpConfig(BaseExpConfig):
    exp_id: str = "recam"
    num_steps: int = 200000
    geometry: GeometryConfig = field(default_factory=GeometryConfig)
    data: DataConfig = field(default_factory=DataConfig)
    model: ModelConfig = field(default_factory=ModelConfig)
    strategy: StrategyConfig = field(default_factory=StrategyConfig)
    dataloader: DataloaderConfig = field(
        default_factory=lambda: DataloaderConfig(batch_size=1, num_workers=2)
    )
    data_manager: DataManagerConfig = field(
        default_factory=lambda: DataManagerConfig(
            pre_encode_batches=1, pre_encode_log_every=2
        )
    )
    ema: EMAConfig = field(default_factory=EMAConfig)
    optimizer: OptimizerConfig = field(
        default_factory=lambda: OptimizerConfig(
            learning_rate=1e-5,
            gradient_checkpoint_modules=["DiTBlock", "Head"],
        )
    )
    lora: LoRAConfig = field(default_factory=lambda: LoRAConfig(enabled=False))
    lr_scheduler: LRSchedulerConfig = field(default_factory=LRSchedulerConfig)
    parallel: ParallelConfig = field(
        default_factory=lambda: ParallelConfig(
            hsdp=True, shard_size=8, zero3=True,
            reshard_after_forward=True, wrap_submodules=["blocks"], cp_size=1,
        )
    )
    logging: LoggingConfig = field(
        default_factory=lambda: LoggingConfig(log_interval=1)
    )
    checkpoint: CheckpointConfig = field(
        default_factory=lambda: CheckpointConfig(
            init_on_meta_device=True,
            save_latest_interval=200,
            save_checkpoint_interval=1000,
        )
    )
    eval: EvalConfig = field(
        default_factory=lambda: EvalConfig(online_eval=False)
    )
    misc: MiscConfig = field(
        default_factory=lambda: MiscConfig(runs_dir="runs")
    )

    def __post_init__(self) -> None:
        super().__post_init__()
        cp_size = self.parallel.cp_size
        if cp_size < 1:
            raise ValueError("parallel.cp_size must be positive")
        if self.parallel.hsdp and cp_size > self.parallel.shard_size:
            raise ValueError(
                "parallel.cp_size must not exceed parallel.shard_size so that each "
                f"CP group stays inside one FSDP shard group; got {cp_size} > "
                f"{self.parallel.shard_size}"
            )
        for n_history_chunks in range(1, self.data.n_chunks):
            tokens = self.geometry.sequence_tokens(n_history_chunks)
            if tokens % cp_size:
                raise ValueError(
                    f"geometry yields {tokens} attention tokens at history depth "
                    f"{n_history_chunks}, which parallel.cp_size={cp_size} cannot "
                    "split evenly; the context-parallel all-to-all deadlocks on an "
                    "uneven split, so pick a geometry whose sequence length is a "
                    "multiple of cp_size at every depth"
                )
        transformer = self.model.transformer
        if tuple(transformer.patch_size) != (1, 2, 2):
            raise ValueError("ReCam requires patch_size == (1,2,2)")
        if transformer.in_dim != 36 or transformer.dim != 5120:
            raise ValueError("ReCam requires transformer in_dim=36 and dim=5120")
