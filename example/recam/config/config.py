MAX_CHUNKS = 22
VAE_TEMPORAL_FACTOR = 4
VAE_SPATIAL_FACTOR = 8
GEOMETRY_SCHEMA_VERSION = 2
COND_IN_CHANNEL = "cond_in_channel"


@dataclass(frozen=True)
class GeometryConfig:
    target_fps: float = 16.0
    height: int = 448
    width: int = 832
    num_frames: int = 33
    overlap: int = 2
    history_pack_shape: tuple[int, int, int] = (2, 8, 8)
    history_pad_shape: tuple[int, int, int] = (2, 56, 104)

    def __post_init__(self) -> None:
        pack_shape = tuple(int(value) for value in self.history_pack_shape)
        pad_shape = tuple(int(value) for value in self.history_pad_shape)
        object.__setattr__(self, "history_pack_shape", pack_shape)
        object.__setattr__(self, "history_pad_shape", pad_shape)
        if not math.isfinite(float(self.target_fps)) or self.target_fps <= 0:
            raise ValueError("geometry.target_fps must be finite and positive")
        if self.height <= 0 or self.width <= 0:
            raise ValueError("geometry height and width must be positive")
        if self.height % (2 * VAE_SPATIAL_FACTOR) or self.width % (2 * VAE_SPATIAL_FACTOR):
            raise ValueError(
                "geometry height and width must be divisible by "
                f"{2 * VAE_SPATIAL_FACTOR}"
            )
        if self.num_frames <= 1 or (self.num_frames - 1) % VAE_TEMPORAL_FACTOR:
            raise ValueError(
                "geometry.num_frames must be 1 modulo the VAE temporal factor"
            )
        if self.overlap < 1 or self.overlap >= self.new_frames:
            raise ValueError(
                "ReCam geometry requires 1 <= overlap < new_frames; "
                f"got overlap={self.overlap}, new_frames={self.new_frames}"
            )
        if len(pack_shape) != 3 or any(value <= 0 for value in pack_shape):
            raise ValueError(
                "geometry.history_pack_shape must contain three positive integers"
            )
        if math.prod(pack_shape) != 128:
            raise ValueError(
                "geometry.history_pack_shape must contain exactly 128 latent values"
            )
        if len(pad_shape) != 3 or any(value <= 0 for value in pad_shape):
            raise ValueError(
                "geometry.history_pad_shape must contain three positive integers"
            )
        temporal_multiple, padded_h, padded_w = pad_shape
        pt, ph, pw = pack_shape
        if temporal_multiple % pt or padded_h % ph or padded_w % pw:
            raise ValueError(
                "geometry.history_pad_shape must be divisible by history_pack_shape"
            )
        latent_h = self.height // VAE_SPATIAL_FACTOR
        latent_w = self.width // VAE_SPATIAL_FACTOR
        if padded_h < latent_h or padded_w < latent_w:
            raise ValueError(
                "geometry.history_pad_shape spatial canvas must cover the "
                f"{latent_h}x{latent_w} latent grid"
            )

    def as_runtime_state(self) -> dict[str, object]:
        return asdict(self)

    @property
    def new_frames(self) -> int:
        """VAE latent frames generated by one chunk."""
        return (self.num_frames - 1) // VAE_TEMPORAL_FACTOR

    def history_frames(self, n_history_chunks: int) -> int:
        """Latent frames the compressed memory holds at one history depth."""
        return self.new_frames * n_history_chunks - self.overlap

    def first_frame_position(self, n_history_chunks: int) -> int:
        """Temporal coordinate of the first frame; the newest memory frame is -1."""
        return -(self.history_frames(n_history_chunks) + 1)

    @property
    def main_frames(self) -> int:
        """Denoised latent frames: overlap + new, with the overlap as the head."""
        return self.overlap + self.new_frames

    @property
    def main_frame_start(self) -> int:
        """First main frame in x; the clean first frame is the only prefix."""
        return 1

    @property
    def tokens_per_latent_frame(self) -> int:
        """Patchified tokens contributed by one latent frame."""
        return (
            self.height // (VAE_SPATIAL_FACTOR * 2)
            * (self.width // (VAE_SPATIAL_FACTOR * 2))
        )

    @property
    def native_latent_frames(self) -> int:
        """Latent frames of the model input: first frame + main."""
        return 1 + self.main_frames

    @property
    def native_tokens(self) -> int:
        return self.native_latent_frames * self.tokens_per_latent_frame

    def memory_tokens(self, n_history_chunks: int) -> int:
        """Packed memory tokens produced for one AR history depth."""
        pt, ph, pw = self.history_pack_shape
        temporal_multiple, padded_h, padded_w = self.history_pad_shape
        history = self.history_frames(n_history_chunks)
        padded = history + (-history) % temporal_multiple
        return (padded // pt) * (padded_h // ph) * (padded_w // pw)

    def sequence_tokens(self, n_history_chunks: int) -> int:
        """Packed self-attention sequence length at one AR history depth."""
        return self.native_tokens + self.memory_tokens(n_history_chunks)


